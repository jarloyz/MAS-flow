def claude_tools(meta: dict, extra: list[str] | None = None) -> str:
    """Runtime tools from the agent's capabilities, plus extra tools (e.g. MCP) from claude_code.agent_tools."""
    tools: list[str] = []
    for capability in meta.get("tools") or []:
        if capability not in CLAUDE_TOOLS:
            die(f"agent '{meta.get('name')}': unknown tool capability '{capability}'")
        tools += [t for t in CLAUDE_TOOLS[capability] if t not in tools]
    tools += [t for t in extra or [] if t not in tools]
    return ", ".join(tools)


def agent_extra_tools(ws: Workspace, name: str) -> list[str]:
    return ws.config.get("claude_code", {}).get("agent_tools", {}).get(name, [])


def mcp_summary(tools: list[str]) -> list[str]:
    """mcp__server__a, mcp__server__b -> mcp:server (compact form for the roster table)."""
    out: list[str] = []
    for tool in tools:
        short = f"mcp:{tool.split('__')[1]}" if tool.startswith("mcp__") else tool
        if short not in out:
            out.append(short)
    return out


def generate_claude(ws: Workspace, agents: dict[str, Agent], values: dict[str, str]) -> list[str]:
    out_agents = ws.root / ".claude" / "agents"
    out_skill = ws.root / ".claude" / "skills" / "masflow" / "SKILL.md"
    written: list[str] = []
    expected: set[Path] = set()

    for name, agent in sorted(agents.items()):
        if agent.is_orchestrator:
            header = (
                "---\nname: masflow\n"
                f"description: {yaml_quote('MAS-Flow orchestrator. /masflow <goal|card> starts a story, /masflow next runs the next pipeline step from handoff.md, /masflow status and /masflow board show state, /masflow map [project|area] maps the product. Delegates every task to MAS-Flow subagents; never writes code.')}\n"
                'argument-hint: "<goal|card> | next | status | board | map [scope]"\n---\n\n'
                f"<!-- {GENERATED_MARK} — edit MAS-Flow/agents or {CONFIG_NAME}, then run `masflow.py sync` -->\n\n"
            )
            content = header + full_prompt(agent, values, CLAUDE_ORCHESTRATOR_ADAPTER)
            if write_if_changed(out_skill, content):
                written.append(str(out_skill.relative_to(ws.root)))
            continue

        shell = CLAUDE_SHELL_NOTE if "shell" in (agent.meta.get("tools") or []) else ""
        header = (
            f"---\nname: {name}\n"
            f"description: {yaml_quote(agent.meta.get('description', name))}\n"
            f"tools: {claude_tools(agent.meta, agent_extra_tools(ws, name))}\n"
            f"model: {agent.meta.get('model', 'inherit')}\n---\n\n"
            f"<!-- {GENERATED_MARK} from {' > '.join(agent.chain)} — do not edit here -->\n\n"
        )
        path = out_agents / f"{name}.md"
        expected.add(path)
        if write_if_changed(path, header + full_prompt(agent, values, CLAUDE_AGENT_ADAPTER.format(shell=shell))):
            written.append(str(path.relative_to(ws.root)))

    # remove stale generated agents (never touch hand-written ones)
    for path in out_agents.glob("*.md") if out_agents.is_dir() else []:
        if path not in expected and GENERATED_MARK in path.read_text(encoding="utf-8"):
            path.unlink()
            written.append(f"removed {path.relative_to(ws.root)}")

    written += write_claude_settings(ws)
    written += write_claude_mcp(ws)
    written += write_claude_memory(ws, agents)
    return written


def write_claude_settings(ws: Workspace) -> list[str]:
    path = ws.root / ".claude" / "settings.json"
    settings = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    hooks_rel = CLAUDE_HOOKS_DIR.relative_to(ws.root) if CLAUDE_HOOKS_DIR.is_relative_to(ws.root) else CLAUDE_HOOKS_DIR
    prefix = '"$CLAUDE_PROJECT_DIR"/' if not Path(hooks_rel).is_absolute() else ""
    ours = {
        "PreToolUse": {"matcher": "Bash", "hooks": [{"type": "command", "command": f"python3 {prefix}{hooks_rel}/command_guard.py"}]},
        "SessionStart": {"hooks": [{"type": "command", "command": f"python3 {prefix}{hooks_rel}/handoff_status.py"}]},
    }
    if any(p.get("format_on_edit") for p in ws.config.get("projects", [])):
        ours["PostToolUse"] = {
            "matcher": "Edit|Write|MultiEdit",
            "hooks": [{"type": "command", "command": f"python3 {prefix}{hooks_rel}/format_on_edit.py", "timeout": 90}],
        }
    hooks = settings.setdefault("hooks", {})
    for event, entry in ours.items():
        kept = [e for e in hooks.get(event, []) if not any(m in json.dumps(e) for m in OWNED_HOOK_MARKERS)]
        hooks[event] = kept + [entry]

    permissions = settings.setdefault("permissions", {})
    for kind in ("allow", "deny"):
        wanted = [ws.expand(rule) for rule in ws.config.get("claude_code", {}).get("permissions", {}).get(kind, [])]
        current = permissions.get(kind, [])
        permissions[kind] = current + [rule for rule in wanted if rule not in current]
    mcp_names = list(ws.config.get("claude_code", {}).get("mcp_servers", {}))
    if mcp_names:
        enabled = settings.get("enabledMcpjsonServers", [])
        settings["enabledMcpjsonServers"] = enabled + [n for n in mcp_names if n not in enabled]
    settings.setdefault("$schema", "https://json.schemastore.org/claude-code-settings.json")

    return [str(path.relative_to(ws.root))] if write_if_changed(path, json.dumps(settings, indent=2, ensure_ascii=False) + "\n") else []


def write_claude_mcp(ws: Workspace) -> list[str]:
    """Merge claude_code.mcp_servers into <workspace>/.mcp.json (servers not declared in the config are kept)."""
    servers = ws.config.get("claude_code", {}).get("mcp_servers", {})
    if not servers:
        return []
    path = ws.root / ".mcp.json"
    current = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    merged = current.setdefault("mcpServers", {})
    for name, server in servers.items():
        merged[name] = json.loads(ws.expand(json.dumps(server)))
    return [str(path.relative_to(ws.root))] if write_if_changed(path, json.dumps(current, indent=2, ensure_ascii=False) + "\n") else []


def write_claude_memory(ws: Workspace, agents: dict[str, Agent]) -> list[str]:
    """Generate .claude/MASFLOW.md (imported from CLAUDE.md with @.claude/MASFLOW.md)."""
    rows = ["| Agent | Model | Tools | Defined in |", "|---|---|---|---|"]
    for name in sorted(agents):
        agent = agents[name]
        if not agent.is_orchestrator:
            rows.append(f"| `{name}` | {agent.meta.get('model', 'inherit')} | {claude_tools(agent.meta, mcp_summary(agent_extra_tools(ws, name)))} | {' > '.join(agent.chain)} |")
    state = ws.config.get("state_dir", ".masflow")
    content = f"""<!-- {GENERATED_MARK} -->
# MAS-Flow in this workspace

This workspace runs the **MAS-Flow** pipeline (methodology in `{MASFLOW_DIR.relative_to(ws.root) if MASFLOW_DIR.is_relative_to(ws.root) else MASFLOW_DIR}/`).

- `/masflow <goal|card>` starts a story (planner → options → you choose), `/masflow next` runs the next step, `/masflow status` / `/masflow board` show the state, `/masflow map [project|area]` maps the product (run it first on a new workspace).
- While running `/masflow`, the main session is the **orchestrator**: it delegates to the subagents below and edits only `{state}/` files.
- Pipeline state: `{state}/handoff.md` (YAML front matter). Task flow: `{state}/board.md`. What the product does: `{state}/product_map.md` (capabilities `CAP-...`, every story links one). Lessons: `{state}/lessons.md` (Active Rules are binding).
- Agents are generated: edit `MAS-Flow/agents/` (methodology), `{state}/agents/` (project-specific) or `{CONFIG_NAME}`, then run `python3 MAS-Flow/scripts/masflow.py sync`.

{chr(10).join(rows)}
"""
    path = ws.root / ".claude" / "MASFLOW.md"
    return [str(path.relative_to(ws.root))] if write_if_changed(path, content) else []


