def cmd_sync(ws: Workspace) -> None:
    agents = resolve_agents(ws)
    if not any(a.is_orchestrator for a in agents.values()):
        die("no orchestrator agent found")
    values = placeholder_values(ws, agents)
    changes = []
    for runtime in ws.config.get("runtimes", ["claude-code"]):
        if runtime not in RUNTIMES:
            die(f"unknown runtime '{runtime}' (available: {', '.join(RUNTIMES)})")
        changes += RUNTIMES[runtime](ws, agents, values)
    print(f"masflow: {len(agents)} agents resolved ({', '.join(sorted(agents))})")
    print("\n".join(f"  updated {c}" for c in changes) if changes else "  everything up to date")


def read_handoff(ws: Workspace) -> tuple[dict, str]:
    path = ws.state("handoff.md")
    if not path.exists():
        die(f"{path} not found (run init)")
    return split_front_matter(path.read_text(encoding="utf-8"))


def cmd_status(ws: Workspace) -> None:
    meta, body = read_handoff(ws)
    if not meta:
        print("handoff.md has no MAS-Flow front matter (legacy format). Run `masflow.py check`.")
        return
    slices = re.findall(r"^\|\s*\d+\s*\|.*?\|\s*(pending|in_progress|closed|rolled_back)\s*\|", body, re.M)
    print(f"Story:   {meta.get('story') or '—'}  {meta.get('title') or ''}".rstrip())
    print(f"Cap.:    {meta.get('capability') or '—'}")
    print(f"Track:   {meta.get('track') or '—'}    Phase: {meta.get('phase')}    Status: {meta.get('status')}")
    if slices:
        print(f"Slices:  {slices.count('closed')}/{len(slices)} closed    current: {meta.get('current_slice')}")
    print(f"Next:    {meta.get('next_agent') or '—'} — {meta.get('next_task') or ''}".rstrip(" —"))
    print(f"Updated: {meta.get('updated_by') or '—'} on {meta.get('updated_at') or '—'}")
    counts = board_counts(ws)
    if counts:
        print("Board:   " + "  ".join(f"{column}: {n}" for column, n in counts.items()))


def cmd_check(ws: Workspace) -> None:
    problems: list[str] = []
    agents = resolve_agents(ws)
    values = placeholder_values(ws, agents)
    for agent in agents.values():
        for key in PLACEHOLDER.findall(agent.body):
            if key not in values:
                problems.append(f"agent {agent.name}: unknown placeholder {{{{{key}}}}}")
        if not agent.meta.get("description"):
            problems.append(f"agent {agent.name}: missing description")
        if not agent.is_orchestrator and not agent.meta.get("tools"):
            problems.append(f"agent {agent.name}: no tools declared")
    for name in ws.config.get("models", {}):
        if name not in agents:
            problems.append(f"config.models: unknown agent '{name}'")
    for name in ws.config.get("claude_code", {}).get("agent_tools", {}):
        if name not in agents:
            problems.append(f"config.claude_code.agent_tools: unknown agent '{name}'")
    for project in ws.config.get("projects", []):
        if not ws.project_path(project).is_dir():
            problems.append(f"project {project.get('name')}: path {ws.project_path(project)} does not exist")
        if not project.get("tests", {}).get("full"):
            problems.append(f"project {project.get('name')}: no tests.full command")
        problems += related_tests.validate_groups(project, ws.project_path(project))
    for template in STATE_TEMPLATES:
        if not ws.state(template).exists():
            problems.append(f"missing state file {ws.state(template)}")
    meta, _ = read_handoff(ws) if ws.state("handoff.md").exists() else ({}, "")
    missing = [k for k in HANDOFF_KEYS if k not in meta]
    if missing:
        problems.append(f"handoff.md front matter missing keys: {', '.join(missing)}")
    if meta.get("next_agent") and meta["next_agent"] not in agents and meta["next_agent"] != "human":
        problems.append(f"handoff.md next_agent '{meta['next_agent']}' is not a known agent")

    drift = map_drift(ws)
    if drift:
        print(f"masflow check: {len(drift)} map entries point to missing paths (run `/masflow map` to refresh):")
        print("\n".join(f"  ~ {d}" for d in drift[:25]) + ("\n  ..." if len(drift) > 25 else ""))

    if problems:
        print("masflow check: problems found")
        print("\n".join(f"  - {p}" for p in problems))
        sys.exit(1)
    print(f"masflow check: OK ({len(agents)} agents, {len(ws.config.get('projects', []))} projects)")


def cmd_related_tests(ws: Workspace, args: argparse.Namespace) -> None:
    project = next((p for p in ws.config.get("projects", []) if p.get("name") == args.project), None)
    if project is None:
        known = ", ".join(p.get("name", "?") for p in ws.config.get("projects", []))
        print(f"masflow: unknown project '{args.project}' (known: {known})", file=sys.stderr)
        sys.exit(2)
    only = None
    if args.only:
        only, ignored = related_tests.normalize_only(ws.project_path(project), args.only)
        for raw in ignored:
            print(f"masflow: warning: --only '{raw}' is outside project '{args.project}'; ignored", file=sys.stderr)
    try:
        result, code = related_tests.related(
            project, ws.project_path(project), lambda text: ws.expand(text, project), args.base, args.group,
            only=only,
        )
    except ValueError as exc:
        print(f"masflow: {exc}", file=sys.stderr)
        sys.exit(2)
    except related_tests.GitError as exc:
        die(f"git failed: {exc}")
    if not code and not result["base_resolved"]:
        print(f"masflow: warning: base '{args.base}' not resolved; using working-tree changes only", file=sys.stderr)
    if code:
        print(f"masflow: {result['error']}. Known groups: {', '.join(result['known_groups']) or '(none)'}", file=sys.stderr)
        sys.exit(code)
    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    elif not result["tests"] and not result["commands"]:
        print("no related tests")
    else:
        print("\n".join(result["commands"]) if result["commands"] else "no related tests")


def board_counts(ws: Workspace) -> dict[str, int]:
    path = ws.state("board.md")
    if not path.exists():
        return {}
    counts, column = {}, None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            column = line[3:].strip()
            if column in BOARD_COLUMNS:
                counts[column] = 0
        elif column in counts and line.lstrip().startswith("- ["):
            counts[column] += 1
    return counts


def map_drift(ws: Workspace) -> list[str]:
    """Paths referenced in the maps (`...` spans that look like files) that no longer exist."""
    drift = []
    pattern = re.compile(r"`((?:/|[\w.-]+/)[\w./-]+\.\w{1,5})(?::\d+)?`")
    for name in MAP_FILES:
        path = ws.state(name)
        if not path.exists():
            continue
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for ref in pattern.findall(line):
                if "<" in ref or "..." in ref:
                    continue
                candidates = [Path(ref)] if ref.startswith("/") else [ws.root / ref] + [ws.project_path(p) / ref for p in ws.config.get("projects", [])]
                if not any(c.exists() for c in candidates):
                    drift.append(f"{name}:{number} {ref}")
    return drift


def ask(question: str, default: str) -> str:
    answer = input(f"{question} [{default}]: ").strip()
    return answer or default


def cmd_init(root: Path, interactive: bool) -> None:
    config_file = root / CONFIG_NAME
    if config_file.exists():
        config = json.loads(config_file.read_text(encoding="utf-8"))
        print(f"masflow: using existing {config_file}")
    else:
        config = json.loads((TEMPLATES_DIR / CONFIG_NAME).read_text(encoding="utf-8"))
        if interactive:
            config["project_name"] = ask("Project name", root.name)
            config["human_language"] = ask("Language to talk to the Human", "English")
            packs = sorted(p.name for p in PACKS_DIR.iterdir() if p.is_dir())
            chosen = ask(f"Stack packs ({', '.join(packs) or 'none available'}), comma-separated", "")
            config["packs"] = [p.strip() for p in chosen.split(",") if p.strip()]
            project = config["projects"][0]
            project["name"] = ask("Main project name", root.name)
            project["path"] = ask("Main project path (relative to workspace)", ".")
            project["description"] = ask("One-line description", "Main application.")
            project["tests"]["full"] = ask("Full test suite command ({project} = project path)", project["tests"]["full"])
            config["git"]["main_branch"] = ask("Main git branch", "main")
        else:
            config["project_name"] = root.name
        config_file.write_text(json.dumps(config, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"masflow: created {config_file} — review projects, test commands and environment rules")

    ws = Workspace(root, config)
    ws.state_dir.mkdir(parents=True, exist_ok=True)
    (ws.state_dir / "agents").mkdir(exist_ok=True)
    for template in STATE_TEMPLATES:
        target = ws.state(template)
        if not target.exists():
            target.write_text((TEMPLATES_DIR / template).read_text(encoding="utf-8"), encoding="utf-8")
            print(f"masflow: created {target.relative_to(root)}")

    if "claude-code" in config.get("runtimes", []):
        claude_md = root / "CLAUDE.md"
        import_line = "@.claude/MASFLOW.md"
        text = claude_md.read_text(encoding="utf-8") if claude_md.exists() else f"# {config['project_name']}\n"
        if import_line not in text:
            claude_md.write_text(text.rstrip() + f"\n\n## MAS-Flow\n\n{import_line}\n", encoding="utf-8")
            print("masflow: CLAUDE.md now imports .claude/MASFLOW.md")

    cmd_sync(ws)
    print("\nNext: fill core_architecture.md with your stack and rules, then run `/masflow status` in Claude Code.")


def main() -> None:
    parser = argparse.ArgumentParser(description="MAS-Flow CLI")
    parser.add_argument("--workspace", help="workspace root (defaults to the nearest directory with masflow.config.json)")
    sub = parser.add_subparsers(dest="command", required=True)
    init = sub.add_parser("init", help="install MAS-Flow in a workspace")
    init.add_argument("--yes", action="store_true", help="non-interactive, use defaults")
    sub.add_parser("sync", help="regenerate runtime agents")
    sub.add_parser("status", help="show handoff state")
    sub.add_parser("check", help="validate config, agents and handoff")
    related = sub.add_parser("related-tests", help="tests related to the changed files of a project")
    related.add_argument("--project", required=True, help="project name from masflow.config.json")
    related.add_argument("--base", default="origin/main", help="base ref for the committed diff (default origin/main)")
    related.add_argument("--group", help="CAP-ID from projects[].test_groups instead of the diff")
    related.add_argument("--only", action="append", default=[], help="restrict changed files to this path (repeatable)")
    related.add_argument("--json",action="store_true", help="print {files_changed, tests, commands} as JSON")
    args = parser.parse_args()

    if args.command == "init":
        root = Path(args.workspace).resolve() if args.workspace else Path.cwd()
        cmd_init(root, interactive=not args.yes and sys.stdin.isatty())
        return
    ws = find_workspace(args.workspace)
    if args.command == "related-tests":
        cmd_related_tests(ws, args)
        return
    {"sync": cmd_sync, "status": cmd_status, "check": cmd_check}[args.command](ws)


if __name__ == "__main__":
    main()
