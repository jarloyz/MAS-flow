# --------------------------------------------------------------------------- utils

def die(msg: str) -> None:
    print(f"masflow: {msg}", file=sys.stderr)
    sys.exit(1)


def parse_scalar(raw: str):
    raw = raw.strip()
    if raw.startswith("[") and raw.endswith("]"):
        return [item.strip().strip("'\"") for item in raw[1:-1].split(",") if item.strip()]
    if raw in ("null", "~", ""):
        return None
    if raw in ("true", "false"):
        return raw == "true"
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "'\"":
        return raw[1:-1]
    return raw


def split_front_matter(text: str) -> tuple[dict, str]:
    """Parse a flat YAML front matter block (key: value, inline lists). Returns (meta, body)."""
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end == -1:
        return {}, text
    meta: dict = {}
    for line in text[4:end].splitlines():
        line = line.split(" #", 1)[0].rstrip()
        if not line.strip() or line.lstrip().startswith("#") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        meta[key.strip()] = parse_scalar(value)
    return meta, text[end + 5:].lstrip("\n")


def yaml_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_if_changed(path: Path, content: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


# --------------------------------------------------------------------------- config

@dataclass
class Workspace:
    root: Path
    config: dict

    @property
    def state_dir(self) -> Path:
        return self.root / self.config.get("state_dir", ".masflow")

    def state(self, name: str) -> Path:
        return self.state_dir / name

    def project_path(self, project: dict) -> Path:
        return (self.root / project.get("path", ".")).resolve()

    def expand(self, text: str, project: dict | None = None) -> str:
        text = text.replace("{workspace}", str(self.root))
        if project is not None:
            text = text.replace("{project}", str(self.project_path(project)))
        return text


def find_workspace(explicit: str | None) -> Workspace:
    candidates = [Path(explicit).resolve()] if explicit else [Path.cwd(), *Path.cwd().parents, MASFLOW_DIR.parent]
    for directory in candidates:
        config_file = directory / CONFIG_NAME
        if config_file.exists():
            try:
                return Workspace(directory, json.loads(config_file.read_text(encoding="utf-8")))
            except json.JSONDecodeError as exc:
                die(f"{config_file}: invalid JSON ({exc})")
    die(f"{CONFIG_NAME} not found. Run `python3 {MASFLOW_DIR.name}/scripts/masflow.py init` in your workspace.")
    raise AssertionError  # unreachable


# --------------------------------------------------------------------------- agents

@dataclass
class AgentSource:
    name: str
    layer: str  # core | pack:<name> | project
    path: Path
    meta: dict
    body: str


@dataclass
class Agent:
    name: str
    meta: dict
    body: str
    chain: list[str] = field(default_factory=list)

    @property
    def is_orchestrator(self) -> bool:
        return self.meta.get("kind") == "orchestrator"


def load_layers(ws: Workspace) -> list[list[AgentSource]]:
    layers: list[tuple[str, Path]] = [("core", CORE_DIR)]
    for pack in ws.config.get("packs", []):
        pack_dir = PACKS_DIR / pack
        if not pack_dir.is_dir():
            die(f"pack '{pack}' not found in {PACKS_DIR}")
        layers.append((f"pack:{pack}", pack_dir))
    layers.append(("project", ws.state("agents")))

    loaded = []
    for label, directory in layers:
        sources = []
        for path in sorted(directory.glob("*.md")) if directory.is_dir() else []:
            if path.name.startswith("_"):
                continue
            meta, body = split_front_matter(path.read_text(encoding="utf-8"))
            if "name" not in meta:
                die(f"{path}: missing 'name' in front matter")
            sources.append(AgentSource(meta["name"], label, path, meta, body))
        loaded.append(sources)
    return loaded


def resolve_agents(ws: Workspace) -> dict[str, Agent]:
    layers = load_layers(ws)

    def lookup(name: str, below: int) -> tuple[int, AgentSource] | None:
        for index in range(below - 1, -1, -1):
            for source in layers[index]:
                if source.name == name:
                    return index, source
        return None

    def build(index: int, source: AgentSource, depth: int = 0) -> Agent:
        if depth > 8:
            die(f"extends chain too deep at {source.path}")
        parent_name = source.meta.get("extends")
        if not parent_name:
            return Agent(source.name, dict(source.meta), source.body.rstrip() + "\n", [source.layer])
        found = lookup(parent_name, index + 1 if parent_name != source.name else index)
        if found is None:
            die(f"{source.path}: extends unknown agent '{parent_name}'")
        base = build(*found, depth + 1)
        meta = {**base.meta, **{k: v for k, v in source.meta.items() if k != "extends"}}
        body = f"{base.body.rstrip()}\n\n---\n\n## SPECIALIZATION: {source.name} ({source.layer})\n\n{source.body.rstrip()}\n"
        return Agent(source.name, meta, body, base.chain + [source.layer])

    agents: dict[str, Agent] = {}
    for index, sources in enumerate(layers):
        for source in sources:
            agents[source.name] = build(index, source)

    for name in ws.config.get("disabled_agents", []):
        agents.pop(name, None)
    for name, model in ws.config.get("models", {}).items():
        if name in agents:
            agents[name].meta["model"] = model
    return agents


# --------------------------------------------------------------------------- rendering

def render_projects(ws: Workspace) -> str:
    lines = ["| Project | Path | Git repo | Description |", "|---|---|---|---|"]
    notes = []
    for project in ws.config.get("projects", []):
        path = ws.project_path(project)
        lines.append(f"| `{project['name']}` | `{path}` | {'yes' if (path / '.git').exists() else 'no'} | {project.get('description', '')} |")
        for note in project.get("notes", []):
            notes.append(f"- **{project['name']}:** {ws.expand(note, project)}")
    return "\n".join(lines + ([""] + notes if notes else []))


def render_environment(ws: Workspace) -> str:
    items = ws.config.get("environment", [])
    return "\n".join(f"- {ws.expand(item)}" for item in items) if items else "- No special environment rules."


def render_tests(ws: Workspace) -> str:
    blocks = []
    for project in ws.config.get("projects", []):
        tests = project.get("tests", {})
        rows = [f"#### `{project['name']}`"]
        for check in tests.get("preflight", []):
            rows.append(f"- **Preflight:** {ws.expand(check, project)}")
        for key, label in (("full", "Full suite"), ("file", "Single file"), ("filter", "Filter")):
            if tests.get(key):
                rows.append(f"- **{label}:** `{ws.expand(tests[key], project)}`")
        if len(rows) == 1:
            rows.append("- No test commands configured — return `needs_human`.")
        blocks.append("\n".join(rows))
    return "\n\n".join(blocks) or "No projects configured."


def render_checks(ws: Workspace) -> str:
    blocks = []
    for project in ws.config.get("projects", []):
        checks = project.get("checks", [])
        if checks:
            blocks.append(f"#### `{project['name']}`\n" + "\n".join(f"- `{ws.expand(c, project)}`" for c in checks))
    return "\n\n".join(blocks) or "No deterministic checks configured: audit by reading the code."


def render_roster(agents: dict[str, Agent]) -> str:
    lines = ["| Agent | Model | Use for |", "|---|---|---|"]
    for name in sorted(agents):
        agent = agents[name]
        if not agent.is_orchestrator:
            lines.append(f"| `{name}` | {agent.meta.get('model', 'inherit')} | {agent.meta.get('description', '')} |")
    return "\n".join(lines)


